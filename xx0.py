def auto_clean(cid):
    try:
        for key, nkey, default in (("autodel", "del_n", 100), ("cleaner", "cl_n", 100)):
            if feat(cid, key):
                n = int(kget(cid, nkey, default))
                cnt = int(kget(cid, "cnt_" + key, "0")) + 1
                if cnt >= n:
                    ids = [r[0] for r in q("SELECT mid FROM msglog WHERE chat=? ORDER BY mid DESC LIMIT ?", cid, n, all=True)]
                    delmsgs(cid, ids)
                    q("DELETE FROM msglog WHERE chat=? AND mid IN (%s)" % (",".join(map(str, ids)) or "0"), cid)
                    cnt = 0
                kset(cid, "cnt_" + key, cnt)
    except Exception as e:
        print("auto_clean", e)


