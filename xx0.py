@cmd("مسح", prefix=True, rk=0)
def c_clear(c, a):
    # مسح + عدد | مسح بالرد | مسح نقاطي... | مسح <قائمة>
    if a.isdigit():
        return need(c, 3) and clear_n(c, int(a))
    sel = {"نقاطي": "points", "رسائلي": "msgs", "سحكاتي": "sahak", "لايكاتي": "likes"}
    if a in sel:
        q(f"UPDATE stats SET {sel[a]}=0 WHERE chat=? AND uid=?", c.cid, c.uid)
        return say(c, "تم")
    if a == "" and c.rep:
        if not need(c, 3):
            return
        ids = [r[0] for r in q("SELECT mid FROM msglog WHERE chat=? AND mid>=? ORDER BY mid", c.cid, c.rep["message_id"], all=True)]
        ids += [c.mid, c.rep["message_id"]]
        return delmsgs(c.cid, set(ids))
    if not need(c, 3, msg=False):
        return
    clear_list(c, a)


def clear_n(c, n):
    ids = [r[0] for r in q("SELECT mid FROM msglog WHERE chat=? ORDER BY mid DESC LIMIT ?", c.cid, n, all=True)]
    ids.append(c.mid)
    delmsgs(c.cid, set(ids))
    q("DELETE FROM msglog WHERE chat=? AND mid IN (%s)" % ",".join(str(i) for i in ids), c.cid)


