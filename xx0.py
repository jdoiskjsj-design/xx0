def deco(text, parse, p):
    """يضيف ايموجي مميز (من لوحة المطور) بداية كل رسالة"""
    ids = em_text_ids()
    if not ids or not text or text.startswith("<tg-emoji"):
        return text
    eid = random.choice(ids)
    if parse == "HTML":
        return f'<tg-emoji emoji-id="{eid}">⭐</tg-emoji> ' + text
    if parse is None:
        p["entities"] = [{"type": "custom_emoji", "offset": 0, "length": 1, "custom_emoji_id": eid}]
        return "⭐ " + text
    return text


def clean_kb(kb, icons=False, tgurl=False):
    if not kb:
        return None
    rows = []
    for row in kb.get("inline_keyboard", []):
        nr = []
        for b in row:
            b = dict(b)
            if icons:
                b.pop("icon_custom_emoji_id", None)
                b.pop("style", None)
            if tgurl and str(b.get("url", "")).startswith("tg://"):
                continue
            nr.append(b)
        if nr:
            rows.append(nr)
    return {"inline_keyboard": rows} if rows else None


def kb_variants(kb):
    out = [kb]
    for v in (clean_kb(kb, icons=True), clean_kb(kb, icons=True, tgurl=True), None):
        if v not in out:
            out.append(v)
    return out


def fatal_err():
    e = (getattr(LASTERR, "e", "") or "").lower()
    return any(x in e for x in ("forbidden", "chat not found", "blocked", "kicked", "deactivated", "too many requests"))


def send(cid, text, kb=None, reply=None, parse="HTML", sec=None, quote=True, **kw):
    SECT.s = sec or "all"
    if quote and text and not text.startswith(("<blockquote", "<tg-emoji")):
        if parse is None:
            text, parse = esc(text), "HTML"
        if parse == "HTML":
            text = "<blockquote>" + text + "</blockquote>"
    base = dict(chat_id=cid, **kw)
    if parse:
        base["parse_mode"] = parse
    if reply:
        base["reply_parameters"] = {"message_id": reply, "allow_sending_without_reply": True}
    r = None
    decs = [True, False] if (em_text_ids() and parse in ("HTML", None)) else [False]
    for dec in decs:
        for k in (kb_variants(kb) if kb else [None]):
            p = dict(base)
            p["text"] = deco(text, parse, p) if dec else text
            if k:
                p["reply_markup"] = k
            r = api("sendMessage", **p)
            if r or fatal_err():
                break
        if r or fatal_err():
            break
    if r and cid < 0:
        log_msg(cid, r["message_id"], BOT_ID, "bot")
    return r


