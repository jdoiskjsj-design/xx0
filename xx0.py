DUR_RE = re.compile(r"(?:^|\s)(?:(\d{1,4})\s*)?(دقيقتين|ساعتين|يومين|دقيقه|دقيقة|دقائق|دقايق|ساعه|ساعة|ساعات|يوم|ايام|أيام)(?=\s|$)")


def split_dur(a):
    """يفصل المدة (مثل 10 دقيقه او ساعتين) عن باقي الكلام. يرجع (النص بدون المدة, الثواني او 0, وصف)"""
    m = DUR_RE.search(a or "")
    if not m:
        return a, 0, ""
    u = m.group(2)
    dual = u.endswith("تين") or u == "يومين"
    n = 2 if dual else int(m.group(1) or 1)
    mul = 60 if u.startswith("د") else 3600 if u.startswith("س") else 86400
    secs = max(60, min(n * mul, 366 * 86400))
    keep = (m.group(1) + " ") if dual and m.group(1) else ""
    return (a[:m.start()] + " " + keep + a[m.end():]).strip(), secs, (f"{n} {u}" if m.group(1) and not dual else u)


