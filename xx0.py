def dev_state(m, s):
    uid = m["from"]["id"]
    step = s["step"]
    text = m.get("text", "")
    if text == "الغاء":
        STATE.pop((uid, uid), None)
        send(uid, "تم الالغاء", parse=None)
        return True
    if step == "emoji_text":
        ids = [e["custom_emoji_id"] for e in (m.get("entities") or []) if e.get("type") == "custom_emoji"]
        ids += re.findall(r"\d{10,}", text)
        if not ids:
            send(uid, "ارسل الايموجي المميز (او ارقامه) او اكتب الغاء", parse=None)
            return True
        sec = s.get("sec", "all")
        cur = [x for x in (kget("g", "emt_" + sec, "") or "").split(",") if x.strip().isdigit()]
        for i in ids:
            if i not in cur:
                cur.append(i)
        kset("g", "emt_" + sec, ",".join(cur))
        send(uid, "تمت الاضافة، ايدي الايموجي:\n" + "\n".join(f"<code>{i}</code>" for i in ids) +
             f"\nالعدد الكلي: {len(cur)}\nارسل المزيد او اكتب الغاء")
        return True
    if step == "al1":
        old = clean_alias(text)
        if not cmd_exists(old):
            send(uid, "هذا الامر غير موجود بالبوت، ارسل امر صحيح (مثل: ايدي) او الغاء", parse=None)
            return True
        s["old"] = old
        s["step"] = "al2"
        send(uid, f"تمام، الامر ({old}). الان ارسل الاسم الجديد الي تريده له", parse=None)
        return True
    if step == "al2":
        new = clean_alias(text)
        if not new or len(new) > 40 or new.startswith("/"):
            send(uid, "اسم غير صالح، ارسل اسم اخر او الغاء", parse=None)
