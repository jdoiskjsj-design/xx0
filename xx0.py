def handle_state(c, m):
    s = STATE.get((c.cid, c.uid))
    if not s:
        return False
    text = m.get("text", "")
    step = s["step"]
    if text.strip() in ("الغاء", "إلغاء"):
        STATE.pop((c.cid, c.uid), None)
        say(c, "تم الالغاء")
        return True
    if step == "set":
        kset(c.cid, s["key"], text)
        say(c, "تم الحفظ")
    elif step == "desc":
        api("setChatDescription", chat_id=c.cid, description=text)
        say(c, "تم")
    elif step == "gphoto":
        if m.get("photo"):
            set_group_photo(c.cid, m["photo"][-1]["file_id"])
            say(c, "تم تغيير الصوره")
        else:
            return False
    elif step == "idtmpl":
        kset(c.cid, "id_tmpl", text)
        say(c, "تم حفظ كليشة الايدي")
    elif step == "idextra":
        kset(c.cid, "id_extra", text)
        say(c, "تم")
    elif step == "ownercl":
        kset(c.cid, "owner_clishe", text)
        say(c, "تم")
    elif step == "rtrig":
        s["trig"] = norm(text)
        s["step"] = "rbody"
        say(c, "الان ارسل الرد (نص او صورة او ملصق او اي ميديا)")
        return True
    elif step == "rbody":
        kind, fid, txt = get_msg_content(m)
        q("INSERT OR REPLACE INTO replies VALUES(?,?,?,?,?,?)", 0 if s.get("g") else c.cid, s["trig"], kind, fid, txt, s.get("special", 0))
        say(c, "تم حفظ الرد")
    elif step == "tag_name":
        nm = text.strip()
        if not nm or len(nm) > 40:
            say(c, "اسم غير صالح، ارسل اسم اقصر من 40 حرف او الغاء")
            return True
        s["name"] = nm
        s["step"] = "tag_user"
        say(c, TAG_ASK_USER.format(name=esc(nm)))
        return True
    elif step == "tag_user":
        u = parse_uname(text)
        if not u:
            say(c, "اليوزر غير صالح، ارسل مثل @username او الغاء")
            return True
        q("INSERT OR REPLACE INTO tag_list VALUES(?,?,?)", c.cid, s["name"], u)
        say(c, TAG_DONE.format(name=esc(s["name"]), u=u))
    elif step == "dtag_name":
        nm = text.strip()
        if not q("SELECT 1 FROM tag_list WHERE chat=? AND name=?", c.cid, nm, one=True):
            say(c, "ما فيه تاك بهذا الاسم، ارسل الاسم الصحيح او الغاء")
            return True
        s["name"] = nm
        s["step"] = "dtag_user"
        say(c, TAGDEL_ASK_USER.format(name=esc(nm)))
        return True
    elif step == "dtag_user":
        row = q("SELECT uname FROM tag_list WHERE chat=? AND name=?", c.cid, s["name"], one=True)
        u = parse_uname(text)
        if not row:
            say(c, "هذا التاك غير موجود")
        elif not u or u.lower() != row[0].lower():
            say(c, "اليوزر ما يطابق التاك، ارسل اليوزر الصحيح او الغاء")
            return True
        else:
            q("DELETE FROM tag_list WHERE chat=? AND name=?", c.cid, s["name"])
            say(c, TAGDEL_DONE.format(name=esc(s["name"]), u=row[0]))
    elif step == "delrep":
        do_delrep(c, text.strip(), s.get("special", 0))
    elif step == "cmd_del":
        v = clean_alias(text)
        if q("SELECT 1 FROM cmds WHERE chat=? AND alias=?", c.cid, v, one=True):
            q("DELETE FROM cmds WHERE chat=? AND alias=?", c.cid, v)
            say(c, "تم مسح الامر")
        else:
            say(c, "ما لقيت امر مضاف بهذا الاسم، ارسل الاسم الصحيح او الغاء")
            return True
    elif step == "cmd1":
        old = clean_alias(text)
        if not cmd_exists(resolve_alias(c.cid, old)) and not cmd_exists(old):
            say(c, "هذا الامر غير موجود بالبوت، ارسل امر صحيح او الغاء")
            return True
        s["old"] = old
        s["step"] = "cmd2"
        say(c, "الان ارسل الامر الجديد")
        return True
    elif step == "cmd2":
        new = clean_alias(text)
        if not new or len(new) > 40:
            say(c, "اسم غير صالح، ارسل اسم اخر او الغاء")
            return True
        if new == s["old"] or cmd_exists(new) or new in DEFAULT_ALIASES:
            say(c, "هذا الاسم محجوز لامر موجود، اختر اسم ثاني او الغاء")
            return True
        q("INSERT OR REPLACE INTO cmds VALUES(?,?,?)", c.cid, new, s["old"])
        say(c, f"تم الحفظ، صار ({esc(new)}) يعمل مثل ({esc(s['old'])})")
    STATE.pop((c.cid, c.uid), None)
    return True


