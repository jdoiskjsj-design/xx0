@cmd("حساب العمر", prefix=True, gate="age")
def c_age(c, a):
    m = re.match(r"(\d{1,4})[/\-.](\d{1,2})[/\-.](\d{1,4})", a)
    if not m:
        return say(c, "اكتب التاريخ هكذا: حساب العمر 2000/5/20")
    x, y, z = int(m.group(1)), int(m.group(2)), int(m.group(3))
    yy, mm, dd = (x, y, z) if x > 31 else (z, y, x)
    try:
        b = datetime.date(yy, mm, dd)
    except ValueError:
        return say(c, "تاريخ غير صحيح")
    t = datetime.datetime.now(TZ).date()
    days = (t - b).days
    if days < 0:
        return say(c, "التاريخ بالمستقبل!")
    years = t.year - b.year - ((t.month, t.day) < (b.month, b.day))
    months = (t.year - b.year) * 12 + t.month - b.month - (t.day < b.day)
    say(c, f"عمرك {years} سنة\nيعني {months} شهر\nاو {days} يوم")


