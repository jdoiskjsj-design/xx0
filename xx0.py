def violation(m, L, edited):
    cid = m["chat"]["id"]
    t = m.get("text") or m.get("caption") or ""
    ents = (m.get("entities") or []) + (m.get("caption_entities") or [])
    et = [e["type"] for e in ents]
    media = any(k in m for k in ("photo", "video", "animation", "sticker", "voice", "audio", "document", "video_note"))
    if edited and "edit" in L:
        return "edit"
    if edited and media and "editmedia" in L:
        return "editmedia"
    if "chat" in L:
        return "chat"
    st = m.get("sticker")
    if st and st.get("set_name") and q("SELECT 1 FROM bpacks WHERE chat=? AND pack=?", cid, st["set_name"], one=True):
        return "pack"
    checks = [
        ("photo", "photo" in m), ("video", "video" in m), ("anim", "animation" in m),
        ("sticker", "sticker" in m and not (st or {}).get("premium_animation")),
        ("premium", bool((st or {}).get("premium_animation")) or "custom_emoji" in et),
        ("voice", "voice" in m), ("audio", "audio" in m), ("files", "document" in m and "animation" not in m),
        ("selfie", "video_note" in m), ("contacts", "contact" in m), ("location", "location" in m or "venue" in m),
        ("forward", "forward_origin" in m or "forward_date" in m),
        ("channels", bool(m.get("sender_chat") and m["sender_chat"]["id"] != cid) or
         (m.get("forward_origin", {}).get("type") == "channel")),
        ("links", "url" in et or "text_link" in et or bool(LINK_RE.search(t))),
        ("usernames", "mention" in et or bool(USER_RE.search(t))),
        ("tag", et.count("mention") + et.count("text_mention") >= 3),
        ("markdown", any(x in et for x in ("bold", "italic", "underline", "strikethrough", "code", "pre", "spoiler", "blockquote"))),
        ("inline", "via_bot" in m), ("whisper", "via_bot" in m and not media), ("whispermedia", "via_bot" in m and media),
        ("clishe", len(t) >= 350), ("english", bool(EN_RE.search(t))), ("persian", bool(FA_RE.search(t))),
        ("zakhrafa", bool(ZAK_RE.search(t))), ("noise", bool(NOISE_RE.search(t)) or len(t) > 2000),
    ]
    for k, v in checks:
        if v and k in L:
            return k
    if t and ({"swear", "porn", "kfr"} & L):
        w = words_of(t)
        nt = norm(t)
        if "swear" in L and (w & {norm(x) for x in SWEAR}):
            return "swear"
        if "porn" in L and (w & {norm(x) for x in PORN}):
            return "porn"
        if "kfr" in L and any(norm(x) in nt for x in KFR):
            return "kfr"
    if "repeat" in L and t:
        k = (cid, m["from"]["id"])
        last = LAST.get(k)
        if last and last[0] == t and now() - last[1] < 30:
            LAST[k] = (t, now(), last[2] + 1)
            if last[2] + 1 >= 3:
                return "repeat"
        else:
            LAST[k] = (t, now(), 1)
    return None


def kinds_of(m, edited):
    ks = []
    for k, n in (("photo", "photo"), ("video", "video"), ("animation", "anim"), ("sticker", "sticker"), ("voice", "voice"),
                 ("audio", "audio"), ("document", "doc"), ("video_note", "note")):
        if k in m:
            ks.append(n)
    if "forward_origin" in m or "forward_date" in m:
        ks.append("fwd")
    t = m.get("text") or m.get("caption") or ""
    if LINK_RE.search(t):
        ks.append("link")
    if edited:
        ks.append("edit")
    return ",".join(ks) or "text"


