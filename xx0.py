    dq.clear()
    q("DELETE FROM ranks WHERE chat=? AND uid=?", cid, uid)
    lst_add(cid, "nomod", uid)
    _tgc.pop((cid, uid), None)
    api("promoteChatMember", chat_id=cid, user_id=uid, can_delete_messages=False, can_restrict_members=False,
        can_pin_messages=False, can_invite_users=False, can_manage_video_chats=False, can_promote_members=False,
        can_change_info=False)
    send(cid, f"تجاوز {ment(uid, name)} حد الحظر ({n} خلال {mins} دقيقة) وتم تنزيله من الاشراف وسحب رتبته تلقائيا")
    return True


