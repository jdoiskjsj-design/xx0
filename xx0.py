def periodic():
    last_az = 0
    last_cl = {}
    while True:
        time.sleep(30)
        try:
            t = now()
            if t - last_az >= 300:
                last_az = t
                for (cid,) in q("SELECT id FROM chats WHERE active=1", all=True):
                    if feat(cid, "azkar_auto"):
                        send(cid, "﴿ " + esc(random.choice(AZKAR)) + " ﴾")
            for (cid,) in q("SELECT id FROM chats WHERE active=1", all=True):
                if feat(cid, "cleaner_time"):
                    mins = int(kget(cid, "cl_t", "60"))
                    if t - last_cl.get(cid, t) >= mins * 60:
                        ids = [r[0] for r in q("SELECT mid FROM msglog WHERE chat=? AND ts>?", cid, t - 172000, all=True)]
                        delmsgs(cid, ids)
                        q("DELETE FROM msglog WHERE chat=?", cid)
                        last_cl[cid] = t
                    last_cl.setdefault(cid, t)
            q("DELETE FROM msglog WHERE ts<?", t - 172800)
        except Exception as e:
            print("periodic", e)


