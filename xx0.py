_FS = {}
_FSWARN = {}


def fsub_conf():
    try:
        v = json.loads(kget("g", "fsub", "") or "{}")
    except Exception:
        v = {}
    return v if v.get("id") else None


def fsub_ok(uid, fresh=False):
    cf = fsub_conf()
    if not cf or uid == DEV_ID or dev_level(uid):
        return True
    k = (cf["id"], uid)
    v = _FS.get(k)
    if v and not fresh and now() - v[1] < (120 if v[0] else 20):
        return v[0]
    r = api("getChatMember", chat_id=cf["id"], user_id=uid)
    if r is None:
        return True  # القناة غير متاحة للبوت: لا نمنع احد (اماناً)
    ok = r.get("status") in ("creator", "administrator", "member") or (r.get("status") == "restricted" and r.get("is_member", True))
    _FS[k] = (ok, now())
    return ok


def fsub_gate(chat_id, uid, reply=None):
    """يرسل رسالة الاشتراك (مرة كل 20 ثانية للشخص)"""
    cf = fsub_conf()
    if now() - _FSWARN.get((chat_id, uid), 0) < 20:
        return
    _FSWARN[(chat_id, uid)] = now()
    btn = []
    if cf.get("url"):
        btn.append(B("اشترك بالقناة", url=cf["url"], style="primary"))
    btn.append(B("تحقق", "fs:chk", style="success"))
    send(chat_id, f"للاستخدام لازم تشترك بقناة البوت اولاً ({esc(cf.get('title', ''))})\nبعد الاشتراك اضغط تحقق",
         kb=KB(btn), reply=reply, sec="cmd")


def fsub_resolve(m):
    text = (m.get("text") or "").strip()
    fo = m.get("forward_origin") or {}
    ref = None
    if fo.get("type") == "channel":
        ref = fo["chat"]["id"]
    else:
        t = re.sub(r"^(https?://)?(t\.me/|telegram\.me/)", "", text).lstrip("@").split("/")[0]
        if re.fullmatch(r"-?\d+", t):
            ref = int(t)
        elif re.fullmatch(r"[A-Za-z]\w{3,31}", t):
            ref = "@" + t
    if ref is None:
        return None, "ارسل يوزر القناة (@username) او ايديها او حوّل رسالة منها"
    ch = api("getChat", chat_id=ref)
    if not ch:
        return None, "ما لقيت القناة، تأكد من اليوزر وان البوت مضاف فيها"
    me = api("getChatMember", chat_id=ch["id"], user_id=BOT_ID)
    if not me or me.get("status") not in ("administrator", "creator"):
        return None, "لازم ترفع البوت مشرف بالقناة اولاً حتى يقدر يتحقق من المشتركين"
    url = ("https://t.me/" + ch["username"]) if ch.get("username") else (api("exportChatInviteLink", chat_id=ch["id"]) or "")
    return {"id": ch["id"], "title": ch.get("title", ""), "url": url}, None


