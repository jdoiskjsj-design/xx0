def xo_cb(cb, p, cid, mid, uid):
    g = XO.get((cid, mid))
    if not g:
        return answer(cb["id"], "انتهت اللعبه", True)
    if p[1] == "join":
        if uid == g["p"][0] or g["p"][1]:
            return answer(cb["id"], "ما تقدر", True)
        g["p"][1] = uid
        g["n"][1] = cb["from"].get("first_name", "")
        edit(cid, mid, f"X: {g['n'][0]}\nO: {g['n'][1]}\nدور: {g['n'][0]}", kb=xo_board(g["b"], mid))
        return answer(cb["id"])
    if not g["p"][1]:
        return answer(cb["id"], "بانتظار لاعب ثاني", True)
    cur = g["p"][g["t"]]
    if uid != cur:
        return answer(cb["id"], "مو دورك", True)
    i = int(p[1])
    if g["b"][i] != " ":
        return answer(cb["id"], "المربع مشغول", True)
    g["b"][i] = "X" if g["t"] == 0 else "O"
    b = g["b"]
    lines = [(0, 1, 2), (3, 4, 5), (6, 7, 8), (0, 3, 6), (1, 4, 7), (2, 5, 8), (0, 4, 8), (2, 4, 6)]
    win = any(b[x] == b[y] == b[z] != " " for x, y, z in lines)
    if win:
        stat_inc(cid, uid, "points", 2)
        edit(cid, mid, f"فاز {g['n'][g['t']]} (+2 نقطة)", kb=xo_board(b, mid))
        XO.pop((cid, mid), None)
    elif " " not in b:
        edit(cid, mid, "تعادل!", kb=xo_board(b, mid))
        XO.pop((cid, mid), None)
    else:
        g["t"] ^= 1
        edit(cid, mid, f"X: {g['n'][0]}\nO: {g['n'][1]}\nدور: {g['n'][g['t']]}", kb=xo_board(b, mid))
    answer(cb["id"])


