def resolve_alias(cid, text):
    rows = q("SELECT alias,target,chat FROM cmds WHERE chat IN (?,0)", cid, all=True) or []
    rows.sort(key=lambda x: (-len(x[0]), 0 if x[2] == cid else 1))
    for al, tg, _ in rows:
        if text == al:
            return tg
    for al, tg, _ in rows:
        if text.startswith(al + " "):
            return tg + text[len(al):]
    for a, t in sorted(DEFAULT_ALIASES.items(), key=lambda x: -len(x[0])):
        if text == a or text.startswith(a + " "):
            return t + text[len(a):]
    return text


